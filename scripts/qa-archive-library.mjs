// Isolated real-browser regression. Never connect to a user's running app/database.
import assert from "node:assert/strict";
import fs from "node:fs/promises";
import { createServer } from "vite";
import { chromium } from "playwright";
const output = "qa-artifacts/archive-library";
await fs.mkdir(output, { recursive: true });
const server = await createServer({ server: { host: "127.0.0.1", port: 4177, strictPort: true } });
await server.listen();
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 960 }, locale: "zh-TW", colorScheme: "dark" });
page.setDefaultTimeout(30_000);
const errors = [];
page.on("pageerror", (error) => errors.push(error.message));
const results = [];
const record = (name) => { results.push(name); console.log(`PASS ${name}`); };
async function view(name) { await page.evaluate(async (name) => { const { useAppStore } = await import("/src/store.ts"); useAppStore.getState().setView(name); }, name); await page.locator(`.workspace.view-${name}`).waitFor(); }
async function dbCheck(fn, arg) { return page.evaluate(fn, arg); }
try {
  await page.addInitScript(() => localStorage.setItem("chengjing-ui", JSON.stringify({ state: { language: "zh-TW", theme: "dark" }, version: 0 })));
  await page.goto("http://127.0.0.1:4177", { waitUntil: "networkidle" });
  await page.locator(".today-page").waitFor();
  const fixture = await page.evaluate(async () => {
    const { db, createCard, createTag } = await import("/src/db.ts");
    const { runWithoutGlobalHistory } = await import("/src/lib/globalHistory.ts");
    const { createKanbanBoard, placeCardOnKanban } = await import("/src/lib/kanban.ts");
    const { useAppStore } = await import("/src/store.ts");
    await runWithoutGlobalHistory(() => db.transaction("rw", db.tables, async () => { for (const table of db.tables) await table.clear(); }));
    const time = Date.now();
    const tag = await createTag("回歸標籤");
    const card = await createCard({ title: "封存生命週期驗證", contentHtml: "<p>封存秘密全文</p>", plainText: "封存秘密全文", tagIds: [tag.id], favorite: true, properties: { 階段: "自訂工作階段", 保留欄位: "不能遺失" } });
    const active = await createCard({ title: "前臺保留卡片", contentHtml: "<p>前臺仍可見</p>", tagIds: [tag.id] });
    const board = await createKanbanBoard("封存測試看板", ["第一欄", "第二欄"]);
    const list = (await db.kanbanLists.where("boardId").equals(board.id).sortBy("order"))[0];
    const placement = await placeCardOnKanban(board.id, list.id, card.id);
    await db.boards.put({ id: "qa-board", title: "封存測試白板", description: "", favorite: false, tagIds: [], createdAt: time, updatedAt: time });
    await db.boardNodes.put({ id: "qa-node", boardId: "qa-board", cardId: card.id, kind: "card", x: 137, y: 211 });
    await db.tasks.bulkPut([{ id: "qa-linked", cardId: card.id, title: "封存來源待辦", done: false, dueAt: time, createdAt: time, updatedAt: time }, { id: "qa-child", parentTaskId: "qa-linked", title: "封存來源子待辦", done: false, createdAt: time, updatedAt: time }, { id: "qa-independent", title: "獨立待辦保留", done: false, createdAt: time, updatedAt: time }]);
    await db.highlights.put({ id: "qa-highlight", cardId: card.id, text: "封存劃記秘密", note: "", color: "amber", createdAt: time });
    useAppStore.getState().openKanbanBoard(board.id);
    return { card: card.id, active: active.id, board: board.id, placement, tag: tag.id };
  });
  const kanbanCard = page.locator(".project-kanban-cards > article").filter({ hasText: "封存生命週期驗證" });
  await kanbanCard.waitFor();
  await kanbanCard.click({ button: "right" });
  await page.locator('[data-context-menu="card"]').getByRole("menuitem", { name: "移到封存", exact: true }).click();
  await kanbanCard.waitFor({ state: "detached" });
  await page.locator(".project-kanban-card-summary").waitFor({ state: "detached" });
  assert.equal(await dbCheck(async (id) => (await (await import("/src/db.ts")).db.cards.get(id)).state, fixture.card), "archived");
  record("right-click archive immediately removes kanban card and inspector");
  await page.reload({ waitUntil: "networkidle" });
  await page.evaluate(async (id) => (await import("/src/store.ts")).useAppStore.getState().openKanbanBoard(id), fixture.board);
  await page.locator(".project-kanban-board").waitFor();
  assert.equal(await kanbanCard.count(), 0);
  assert.deepEqual(await dbCheck(async (id) => (await import("/src/db.ts")).db.kanbanPlacements.get(id), fixture.placement.id), fixture.placement);
  record("archive survives reload without deleting placement");
  for (const name of ["today", "tasks", "highlights"]) {
    await view(name);
    await page.locator(name === "today" ? ".today-page" : name === "tasks" ? ".task-section" : ".highlight-list").first().waitFor();
    assert.equal(await page.locator(".workspace").getByText("封存生命週期驗證", { exact: true }).count(), 0);
    assert.equal(await page.locator('[data-task-id="qa-linked"], [data-task-id="qa-child"]').count(), 0);
    assert.equal(await page.locator(".highlight-card").filter({ hasText: "封存劃記秘密" }).count(), 0);
  }
  record("today, task timeline and highlights exclude archived sources");
  await page.evaluate(async () => (await import("/src/store.ts")).useAppStore.getState().openBoard("qa-board"));
  await page.locator(".react-flow").waitFor();
  assert.equal(await page.locator('.react-flow__node[data-id="qa-node"]').count(), 0);
  record("whiteboard hides archived nodes");
  await page.evaluate(async () => (await import("/src/store.ts")).useAppStore.getState().setCommandOpen(true));
  await page.locator(".command-input input").fill("封存生命週期驗證");
  await page.waitForFunction(() => !document.querySelector(".command-results")?.textContent.includes("封存生命週期驗證") || document.querySelectorAll(".command-results > button").length === 0);
  assert.equal(await page.locator(".command-results > button").count(), 0);
  await page.locator(".command-input input").press("Escape");
  record("global search excludes archived cards");
  await view("library");
  await page.locator(".library-card").filter({ hasText: "前臺保留卡片" }).waitFor();
  assert.equal(await page.locator(".sidebar").getByRole("button", { name: "資料庫", exact: true }).count(), 0);
  assert.equal(await page.locator(".library-card").filter({ hasText: "封存生命週期驗證" }).count(), 0);
  await page.locator(`[data-library-tag="${fixture.tag}"] b`).getByText("1", { exact: true }).waitFor();
  await page.locator('.library-content > .collection-tabs').getByRole("button", { name: "封存", exact: true }).click();
  const archivedCard = page.locator(".library-card").filter({ hasText: "封存生命週期驗證" });
  await archivedCard.waitFor();
  await archivedCard.click();
  await page.locator(".card-editor-panel").getByText("封存秘密全文", { exact: true }).first().waitFor();
  await page.evaluate(async () => (await import("/src/store.ts")).useAppStore.getState().closeCard());
  await archivedCard.click({ button: "right" });
  await page.locator('[data-context-menu="card"]').getByRole("menuitem", { name: /還原到卡片庫|移回卡片庫|返回卡片庫|恢復到卡片庫/ }).click();
  await archivedCard.waitFor({ state: "detached" });
  record("archive is readable only from archive and supports restore");
  await page.evaluate(async (id) => (await import("/src/store.ts")).useAppStore.getState().openKanbanBoard(id), fixture.board);
  await kanbanCard.waitFor();
  await view("tasks");
  await page.locator('[data-task-id="qa-linked"]').waitFor();
  await page.locator('[data-task-id="qa-child"]').waitFor();
  await view("highlights");
  await page.locator(".highlight-card").filter({ hasText: "封存劃記秘密" }).waitFor();
  record("restore reinstates original kanban position, tasks and highlights");
  await view("library");
  await page.locator(`[data-library-tag="${fixture.tag}"]`).click();
  await page.locator(".library-content .view-toggle").getByRole("button", { name: "表格檢視", exact: true }).click();
  const row = page.locator(`[data-library-row="${fixture.card}"]`);
  await row.waitFor();
  assert.equal(await page.locator("[data-library-row]").count(), 2);
  await page.locator(`[data-library-task="qa-linked"]`).waitFor();
  assert.equal(await page.locator(`[data-library-task="qa-independent"]`).count(), 0);
  await page.locator(".library-content .view-toggle").getByRole("button", { name: "階段視圖", exact: true }).click();
  await page.locator(`[data-library-stage-card="${fixture.card}"]`).waitFor();
  await page.locator(".library-stage-board > section > header").getByText("自訂工作階段", { exact: true }).waitFor();
  await page.locator(".library-content .view-toggle").getByRole("button", { name: "表格檢視", exact: true }).click();
  await row.locator("select").selectOption("研究中");
  await page.waitForFunction(async (id) => (await (await import("/src/db.ts")).db.cards.get(id)).properties.階段 === "研究中", fixture.card);
  assert.equal(await dbCheck(async (id) => (await (await import("/src/db.ts")).db.cards.get(id)).properties.保留欄位, fixture.card), "不能遺失");
  record("tag filter shared across views; tasks inherit source tags; custom stages/properties survive");
  await page.locator(`[data-library-tag="${fixture.tag}"]`).click({ button: "right" });
  await page.locator('[data-context-menu="tag"]').getByRole("menuitem", { name: "重新命名標籤", exact: true }).click();
  await page.locator(".tag-rename-dialog input").fill("重新命名後的標籤");
  await page.locator(".tag-rename-dialog input").press("Enter");
  await row.getByText("重新命名後的標籤", { exact: true }).waitFor();
  record("tag rename propagates to cards and structured view");
  await page.getByRole("button", { name: "批次選取", exact: true }).click();
  await page.getByRole("button", { name: "選取目前 2 張", exact: true }).click();
  assert.equal(await page.locator("[data-library-row].is-selected").count(), 2);
  await page.locator('[role="toolbar"]').getByRole("button", { name: "移到垃圾桶", exact: true }).click();
  await row.waitFor({ state: "detached" });
  assert.equal(await dbCheck(async (id) => (await (await import("/src/db.ts")).db.cards.get(id)).state, fixture.card), "trash");
  record("structured-view batch selection and trash preserved");
  // Restore fixtures for visual/layout inspection, no user data exists in this browser context.
  await dbCheck(async (ids) => { const { db } = await import("/src/db.ts"); for (const id of ids) await db.cards.update(id, { state: "active" }); }, [fixture.card, fixture.active]);
  await row.waitFor();
  await page.screenshot({ path: `${output}/desktop-library.png` });
  await page.setViewportSize({ width: 960, height: 900 });
  const overflow = await page.locator(".library-content").evaluate((el) => el.scrollWidth > el.clientWidth + 2);
  assert.equal(overflow, false, "library table must scroll inside its own wrapper, not overflow workspace");
  await page.screenshot({ path: `${output}/narrow-library.png` });
  record("desktop and minimum-window library layouts stay contained");
  assert.deepEqual(errors, [], "browser runtime errors");
} catch (error) {
  await page.screenshot({ path: `${output}/failure.png` }).catch(() => {});
  console.error("URL", page.url(), "BODY", (await page.locator("body").innerText()).slice(-9000));
  throw error;
} finally {
  await fs.writeFile(`${output}/results.json`, JSON.stringify({ passed: results.length, cases: results, errors }, null, 2));
  await browser.close(); await server.close();
}
